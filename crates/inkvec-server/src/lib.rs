//! Inkvec's HTTP service: the raster-to-SVG facade (`inkvec`) behind axum.
//!
//! One rule holds this crate to the same "one source of truth" discipline as every other
//! binding: it does not know what an option is. `inkvec::Options` is parsed from a JSON
//! object built here purely mechanically -- from a `?options=` query parameter, an
//! `X-Inkvec-Options` header, a multipart `options` part, and generic query parameters typed
//! against `inkvec::options_schema_json()` -- and handed to [`inkvec::Options::from_json`],
//! whose validation errors become the response. No option is named in this file.
//!
//! [`app`] builds the router; [`AppState`] carries the concurrency limiter, body-size cap
//! and optional time budget/timeout read from the environment (see the crate README for the
//! `INKVEC_*` variables). `main.rs` is a thin binary wrapper around this library so the
//! integration tests (`tests/`) can build the same router in-process.

use axum::{
    body::{to_bytes, Body},
    extract::State,
    http::{header, HeaderMap, StatusCode, Uri},
    response::{IntoResponse, Response},
    routing::{get, post},
    Json, Router,
};
use futures_util::TryStreamExt;
use serde_json::{json, Map, Value};
use std::net::SocketAddr;
use std::sync::{Arc, OnceLock};
use std::time::Duration;
use tokio::sync::Semaphore;

/// The generated OpenAPI 3.1 document (`bindings/openapi.json`), served verbatim at
/// `/openapi.json`. Generated by `bindings/codegen/openapi.py` from
/// `bindings/options.schema.json`; `bindings/codegen/generate.py --check` covers it.
pub const OPENAPI_JSON: &str = include_str!("../../../bindings/openapi.json");

/// Default request body limit, in bytes (20 MB), when `INKVEC_MAX_BODY_BYTES` is unset.
pub const DEFAULT_MAX_BODY_BYTES: usize = 20 * 1024 * 1024;

/// Default per-request server-side time cap, in seconds, when `INKVEC_REQUEST_TIMEOUT_SECS`
/// is unset. 0 (via the environment variable) disables the cap.
pub const DEFAULT_REQUEST_TIMEOUT_SECS: u64 = 60;

/// Shared state behind every handler. Cheap to clone: everything is an `Arc` or `Copy`.
#[derive(Clone)]
pub struct AppState {
    /// Bounds how many traces run at once. A request that finds no permit free is rejected
    /// immediately with `503 busy` rather than queued, so load sheds instead of piling up
    /// behind a CPU-bound endpoint.
    semaphore: Arc<Semaphore>,
    /// Maximum accepted request body, in bytes (checked while reading, not just
    /// `Content-Length`, so a chunked or lying body cannot bypass it).
    max_body_bytes: usize,
    /// If set, and the caller's options do not already set `time_budget`, this value is
    /// merged in before validation -- the facade's own advisory budget, applied as a server
    /// default rather than a client requirement. `None` leaves the facade default (no budget).
    default_time_budget: Option<f64>,
    /// If set, the whole trace (decode + pipeline) is capped at this wall-clock duration.
    /// This is a coarse, server-side backstop: dropping the future when it elapses does not
    /// stop the blocking thread running the trace (Rust cannot cancel a running OS thread),
    /// so an abandoned trace keeps consuming a worker thread until it finishes on its own.
    /// See the README's "known limitations".
    request_timeout: Option<Duration>,
    /// Parsed once from `inkvec::options_schema_json()`, used only to type generic query
    /// parameters (`?colors=8` -> the JSON number `8`, `?no_background=true` -> the JSON
    /// bool `true`). The set of recognised keys, and what a value means, come from the
    /// schema; nothing here is named.
    options_schema: Arc<Value>,
}

impl AppState {
    /// Read every `INKVEC_*` configuration variable from the process environment. Never
    /// panics on a bad value; a variable that fails to parse is logged and its default used.
    pub fn from_env() -> Self {
        let cores = std::thread::available_parallelism()
            .map(std::num::NonZeroUsize::get)
            .unwrap_or(1);
        let max_concurrency = env_usize("INKVEC_MAX_CONCURRENCY", cores);
        let max_body_bytes = env_usize("INKVEC_MAX_BODY_BYTES", DEFAULT_MAX_BODY_BYTES);
        let default_time_budget = std::env::var("INKVEC_DEFAULT_TIME_BUDGET")
            .ok()
            .and_then(|s| s.trim().parse::<f64>().ok())
            .filter(|v| v.is_finite() && *v > 0.0);
        let timeout_secs = env_u64("INKVEC_REQUEST_TIMEOUT_SECS", DEFAULT_REQUEST_TIMEOUT_SECS);
        let request_timeout = (timeout_secs > 0).then(|| Duration::from_secs(timeout_secs));
        Self::new(
            max_concurrency,
            max_body_bytes,
            default_time_budget,
            request_timeout,
        )
    }

    /// Construct directly, bypassing the environment: for tests, and for an embedder that
    /// wants to configure the service programmatically instead of through `INKVEC_*`
    /// variables. `max_concurrency` below 1 is treated as 1.
    pub fn new(
        max_concurrency: usize,
        max_body_bytes: usize,
        default_time_budget: Option<f64>,
        request_timeout: Option<Duration>,
    ) -> Self {
        let options_schema: Value =
            serde_json::from_str(inkvec::options_schema_json()).unwrap_or(Value::Null);
        AppState {
            semaphore: Arc::new(Semaphore::new(max_concurrency.max(1))),
            max_body_bytes,
            default_time_budget,
            request_timeout,
            options_schema: Arc::new(options_schema),
        }
    }

    /// The port to bind, from `INKVEC_PORT` (default 8080).
    pub fn port() -> u16 {
        std::env::var("INKVEC_PORT")
            .ok()
            .and_then(|s| s.trim().parse().ok())
            .unwrap_or(8080)
    }

    /// A clone of the concurrency semaphore, for a caller (a test) that wants to hold a
    /// permit itself to deterministically exercise the `503 busy` path without a timing
    /// race against real trace latency.
    pub fn concurrency_semaphore(&self) -> Arc<Semaphore> {
        self.semaphore.clone()
    }
}

fn env_usize(name: &str, default: usize) -> usize {
    std::env::var(name)
        .ok()
        .and_then(|s| s.trim().parse().ok())
        .unwrap_or(default)
}

fn env_u64(name: &str, default: u64) -> u64 {
    std::env::var(name)
        .ok()
        .and_then(|s| s.trim().parse().ok())
        .unwrap_or(default)
}

/// The router: every endpoint in the README's table, wired to `state`.
pub fn app(state: AppState) -> Router {
    Router::new()
        .route("/trace", post(trace))
        .route("/options/schema", get(options_schema))
        .route("/options/defaults", get(options_defaults))
        .route("/healthz", get(healthz))
        .route("/version", get(version))
        .route("/openapi.json", get(openapi))
        .with_state(state)
}

