// ---------------------------------------------------------------------------------------
// POST /trace
// ---------------------------------------------------------------------------------------

async fn trace(
    State(state): State<AppState>,
    headers: HeaderMap,
    uri: Uri,
    body: Body,
) -> Response {
    match trace_inner(state, headers, uri, body).await {
        Ok(resp) => resp,
        Err(e) => e.into_response(),
    }
}

async fn trace_inner(
    state: AppState,
    headers: HeaderMap,
    uri: Uri,
    body: Body,
) -> Result<Response, ApiError> {
    // Shed load rather than queue: a CPU-bound endpoint that queued would just move the
    // wait from the network into memory.
    let _permit = state
        .semaphore
        .clone()
        .try_acquire_owned()
        .map_err(|_| ApiError::Busy)?;

    let content_type = headers
        .get(header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .unwrap_or("")
        .to_string();

    let query_pairs: Vec<(String, String)> = uri
        .query()
        .map(|q| form_urlencoded::parse(q.as_bytes()).into_owned().collect())
        .unwrap_or_default();

    let (image, options_from_body) = if content_type_is(&content_type, "multipart/form-data") {
        read_multipart(body, &content_type, state.max_body_bytes).await?
    } else {
        let bytes = to_bytes(body, state.max_body_bytes).await.map_err(|_| {
            ApiError::TooLarge(format!("body exceeds {} bytes", state.max_body_bytes))
        })?;
        (bytes.to_vec(), None)
    };

    if image.is_empty() {
        return Err(ApiError::InvalidImage(
            "no image bytes in the request".into(),
        ));
    }

    let merged = merge_options(&state, &query_pairs, &headers, options_from_body.as_deref())?;
    let mut opts = inkvec::Options::from_json(&merged.to_string()).map_err(ApiError::from)?;
    if let Some(budget) = state.default_time_budget {
        if merged.get("time_budget").is_none() {
            opts.time_budget = budget;
        }
    }

    let traced = run_trace(image, opts, state.request_timeout).await?;

    let mut response = Response::builder()
        .status(StatusCode::OK)
        .header(header::CONTENT_TYPE, "image/svg+xml")
        .header("X-Inkvec-Width", traced.width)
        .header("X-Inkvec-Height", traced.height)
        .body(Body::from(traced.svg))
        .unwrap_or_else(|_| StatusCode::INTERNAL_SERVER_ERROR.into_response());
    response.headers_mut().insert(
        header::CACHE_CONTROL,
        header::HeaderValue::from_static("no-store"),
    );
    Ok(response)
}

/// Run the trace on the blocking pool, under an optional wall-clock cap.
///
/// The cap is a backstop, not a cancellation: dropping the timed-out future stops *waiting*
/// for the blocking task, but the task itself (already handed to the blocking pool) keeps
/// running to completion or panic, since Rust has no way to interrupt a running OS thread.
/// See `AppState::request_timeout` and the README.
async fn run_trace(
    image: Vec<u8>,
    opts: inkvec::Options,
    timeout: Option<Duration>,
) -> Result<inkvec::Traced, ApiError> {
    let work = tokio::task::spawn_blocking(move || inkvec::trace(&image, &opts));
    let joined = match timeout {
        Some(d) => tokio::time::timeout(d, work).await.map_err(|_| {
            ApiError::Internal(format!(
                "trace exceeded the server's request timeout of {:.1}s; time_budget is advisory \
                 and cannot guarantee this on its own",
                d.as_secs_f64()
            ))
        })?,
        None => work.await,
    };
    let result = joined.map_err(|e| ApiError::Internal(format!("the trace task panicked: {e}")))?;
    result.map_err(ApiError::from)
}

/// Read a `multipart/form-data` body: the `image` part's bytes and, if present, the
/// `options` part's text (unparsed JSON, merged in by [`merge_options`]).
async fn read_multipart(
    body: Body,
    content_type: &str,
    max_body_bytes: usize,
) -> Result<(Vec<u8>, Option<String>), ApiError> {
    let boundary = multer::parse_boundary(content_type)
        .map_err(|e| ApiError::InvalidImage(format!("bad multipart boundary: {e}")))?;
    let stream = body.into_data_stream().map_err(std::io::Error::other);
    let constraints = multer::Constraints::new()
        .size_limit(multer::SizeLimit::new().whole_stream(max_body_bytes as u64));
    let mut multipart = multer::Multipart::with_constraints(stream, boundary, constraints);

    let mut image: Option<Vec<u8>> = None;
    let mut options: Option<String> = None;
    loop {
        let field = multipart.next_field().await.map_err(map_multer_error)?;
        let Some(field) = field else { break };
        match field.name().unwrap_or("") {
            "image" => {
                let bytes = field.bytes().await.map_err(map_multer_error)?;
                image = Some(bytes.to_vec());
            }
            "options" => {
                let text = field.text().await.map_err(map_multer_error)?;
                options = Some(text);
            }
            _ => {
                // An unrecognised part is ignored rather than rejected: this endpoint has
                // exactly two named parts, and a client sending an extra one (a filename
                // field from a browser form, say) should not fail the request.
            }
        }
    }
    let image =
        image.ok_or_else(|| ApiError::InvalidImage("multipart body has no `image` part".into()))?;
    Ok((image, options))
}

fn map_multer_error(e: multer::Error) -> ApiError {
    if matches!(
        e,
        multer::Error::StreamSizeExceeded { .. } | multer::Error::FieldSizeExceeded { .. }
    ) {
        ApiError::TooLarge(e.to_string())
    } else {
        ApiError::InvalidImage(format!("bad multipart body: {e}"))
    }
}

fn content_type_is(content_type: &str, wanted: &str) -> bool {
    content_type
        .split(';')
        .next()
        .unwrap_or("")
        .trim()
        .eq_ignore_ascii_case(wanted)
}

// ---------------------------------------------------------------------------------------
// Options: query params, header, and the multipart JSON part merged, schema-typed, then
// handed to inkvec::Options::from_json for the one real validation pass.
// ---------------------------------------------------------------------------------------

/// Build the JSON object passed to [`inkvec::Options::from_json`], from lowest to highest
/// priority: generic query parameters typed against the schema, then `?options=`, then
/// `X-Inkvec-Options`, then (for multipart requests) the `options` part. A later source
/// overrides a key an earlier one set; nothing here is validated beyond typing a query
/// parameter's string against the schema's declared type -- range and unknown-key checks are
/// the facade's, in `Options::from_json`.
fn merge_options(
    state: &AppState,
    query_pairs: &[(String, String)],
    headers: &HeaderMap,
    body_options: Option<&str>,
) -> Result<Value, ApiError> {
    let mut merged = Map::new();

    let generic = typed_query_options(&state.options_schema, query_pairs)?;
    merge_into(&mut merged, generic);

    if let Some((_, raw)) = query_pairs.iter().find(|(k, _)| k == "options") {
        merge_into(
            &mut merged,
            parse_options_object(raw, "the `options` query parameter")?,
        );
    }

    if let Some(raw) = headers
        .get("X-Inkvec-Options")
        .and_then(|v| v.to_str().ok())
    {
        merge_into(
            &mut merged,
            parse_options_object(raw, "the X-Inkvec-Options header")?,
        );
    }

    if let Some(raw) = body_options {
        merge_into(
            &mut merged,
            parse_options_object(raw, "the multipart `options` part")?,
        );
    }

    Ok(Value::Object(merged))
}

fn merge_into(target: &mut Map<String, Value>, source: Map<String, Value>) {
    for (k, v) in source {
        target.insert(k, v);
    }
}

fn parse_options_object(raw: &str, from: &str) -> Result<Map<String, Value>, ApiError> {
    let raw = raw.trim();
    if raw.is_empty() {
        return Ok(Map::new());
    }
    match serde_json::from_str::<Value>(raw) {
        Ok(Value::Object(m)) => Ok(m),
        Ok(_) => Err(ApiError::InvalidOptions(format!(
            "{from} must be a JSON object"
        ))),
        Err(e) => Err(ApiError::InvalidOptions(format!(
            "{from} is not valid JSON: {e}"
        ))),
    }
}

/// Query parameters whose key is a property of the options schema, converted to that
/// property's JSON type (`boolean`, `integer`, `number` or `string`). A key the schema does not have is
/// left for `Options::from_json` to reject (or, for `options`, is not an option at all and is
/// skipped here). A value that does not parse as its schema type is `invalid_options` naming
/// the key, the same shape of error the facade itself returns.
fn typed_query_options(
    schema: &Value,
    query_pairs: &[(String, String)],
) -> Result<Map<String, Value>, ApiError> {
    let properties = schema.get("properties").and_then(Value::as_object);
    let mut out = Map::new();
    let Some(properties) = properties else {
        return Ok(out);
    };
    for (key, raw) in query_pairs {
        if key == "options" {
            continue;
        }
        let Some(prop) = properties.get(key) else {
            continue; // not an option; Options::from_json will reject it if it is meant as one
        };
        let kind = prop.get("type").and_then(Value::as_str).unwrap_or("");
        let value = match kind {
            "boolean" => parse_query_bool(key, raw)?,
            "integer" | "number" => raw
                .trim()
                .parse::<f64>()
                .ok()
                .filter(|v| v.is_finite())
                .map(|v| json_number(v, kind == "integer"))
                .ok_or_else(|| {
                    ApiError::InvalidOptions(format!("`{key}` must be a {kind}, got {raw:?}"))
                })?,
            // Taken as written; `Options::from_json` validates what it means.
            "string" => Value::String(raw.clone()),
            _ => continue,
        };
        out.insert(key.clone(), value);
    }
    Ok(out)
}

fn parse_query_bool(key: &str, raw: &str) -> Result<Value, ApiError> {
    match raw.trim().to_ascii_lowercase().as_str() {
        "true" | "1" => Ok(Value::Bool(true)),
        "false" | "0" => Ok(Value::Bool(false)),
        _ => Err(ApiError::InvalidOptions(format!(
            "`{key}` must be a bool (true/false/1/0), got {raw:?}"
        ))),
    }
}

fn json_number(v: f64, as_integer: bool) -> Value {
    if as_integer && v.fract() == 0.0 && v >= 0.0 && v <= u64::MAX as f64 {
        Value::from(v as u64)
    } else {
        serde_json::Number::from_f64(v)
            .map(Value::Number)
            .unwrap_or(Value::Null)
    }
}

