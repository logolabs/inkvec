/// The service's own error kinds, one more (`too_large`, `busy`) than the facade's
/// [`inkvec::Error`] -- both bodies as `{ "error": { "code": ..., "message": ... } }`.
#[derive(Debug)]
enum ApiError {
    InvalidImage(String),
    InvalidOptions(String),
    Internal(String),
    TooLarge(String),
    Busy,
}

impl ApiError {
    fn code(&self) -> &'static str {
        match self {
            ApiError::InvalidImage(_) => "invalid_image",
            ApiError::InvalidOptions(_) => "invalid_options",
            ApiError::Internal(_) => "internal",
            ApiError::TooLarge(_) => "too_large",
            ApiError::Busy => "busy",
        }
    }

    fn status(&self) -> StatusCode {
        match self {
            ApiError::InvalidImage(_) => StatusCode::BAD_REQUEST,
            ApiError::InvalidOptions(_) => StatusCode::UNPROCESSABLE_ENTITY,
            ApiError::Internal(_) => StatusCode::INTERNAL_SERVER_ERROR,
            ApiError::TooLarge(_) => StatusCode::PAYLOAD_TOO_LARGE,
            ApiError::Busy => StatusCode::SERVICE_UNAVAILABLE,
        }
    }

    fn message(&self) -> String {
        match self {
            ApiError::InvalidImage(m)
            | ApiError::InvalidOptions(m)
            | ApiError::Internal(m)
            | ApiError::TooLarge(m) => m.clone(),
            ApiError::Busy => "the server is at its concurrency limit; try again shortly".into(),
        }
    }
}

impl From<inkvec::Error> for ApiError {
    fn from(e: inkvec::Error) -> Self {
        let message = e.message().to_string();
        match e.code() {
            "invalid_image" => ApiError::InvalidImage(message),
            "invalid_options" => ApiError::InvalidOptions(message),
            _ => ApiError::Internal(message),
        }
    }
}

impl IntoResponse for ApiError {
    fn into_response(self) -> Response {
        if matches!(self, ApiError::Internal(_)) {
            tracing::error!(message = %self.message(), "internal error");
        }
        let status = self.status();
        let body = json!({ "error": { "code": self.code(), "message": self.message() } });
        (status, Json(body)).into_response()
    }
}

